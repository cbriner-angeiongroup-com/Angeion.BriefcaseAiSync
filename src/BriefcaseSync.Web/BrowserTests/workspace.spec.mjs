import { test, expect } from '@playwright/test';
test('overview, filtering, theme and mobile navigation', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Sync overview' })).toBeVisible();
  await expect(page.getByText('Synthetic workspace', { exact: false }).first()).toBeVisible();
  await page.getByLabel('Filter deliveries').selectOption('UpdateRequired');
  await expect(page.getByRole('button', { name: 'Inspect case 10425' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Inspect case 10427' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Inspect case 10425' }).click();
  await expect(page.getByRole('region', { name: 'Delivery details' })).toBeVisible();
  await page.getByRole('button', { name: 'Toggle dark theme' }).click();
  await expect(page.locator('html')).toHaveClass(/dark/);
  await page.screenshot({ path: '../../artifacts/ui/overview-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Preview a case', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Case sync preview' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: '../../artifacts/ui/preview-mobile.png', fullPage: true });
});
