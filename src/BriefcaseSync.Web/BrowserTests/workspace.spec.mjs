test('configuration validates and persists changes across page reloads', async ({ page }) => {
  await page.goto('/configuration');
  await page.getByLabel('Sync schedule (UTC cron)').fill('not a cron');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('alert')).toContainText('Check the UTC cron');
  await page.getByLabel('Sync schedule (UTC cron)').fill('*/20 * * * *');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('saved in this synthetic workspace');
  await page.reload();
  await expect(page.getByLabel('Sync schedule (UTC cron)')).toHaveValue('*/20 * * * *');
  await page.screenshot({ path: '../../artifacts/ui/configuration.png', fullPage: true });
});

test('document type mappings validate, persist and fit narrow screens', async ({ page }) => {
  await page.goto('/configuration');
  await expect(page.getByRole('heading', { name: 'Document type mappings', exact: true })).toBeVisible();
  await expect(page.getByLabel('SmartAdvocate type 1', { exact: true })).toHaveValue('Signed Retainer Agreement');
  await expect(page.getByLabel('BriefCase type 1', { exact: true })).toHaveValue('Signed Retainer Agreement');
  await page.getByRole('button', { name: 'Add document type mapping', exact: true }).click();
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('alert')).toContainText('Check document type mappings');
  await page.getByLabel('SmartAdvocate type 7', { exact: true }).fill('Signed Retainer Agreement');
  await page.getByLabel('BriefCase type 7', { exact: true }).selectOption('Other');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('alert')).toContainText('must be unique');
  await page.getByLabel('SmartAdvocate type 7', { exact: true }).fill('SA Signed Retainer Agreement');
  await page.getByLabel('BriefCase type 7', { exact: true }).selectOption('Signed Retainer Agreement');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('saved in this synthetic workspace');
  await page.reload();
  await expect(page.getByLabel('SmartAdvocate type 7', { exact: true })).toHaveValue('SA Signed Retainer Agreement');
  await expect(page.getByLabel('BriefCase type 7', { exact: true })).toHaveValue('Signed Retainer Agreement');
  await page.getByRole('button', { name: 'Remove document type mapping 7', exact: true }).click();
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('saved in this synthetic workspace');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('heading', { name: 'Document type mappings', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: '../../artifacts/ui/document-types-mobile.png', fullPage: true });
  await page.getByLabel('BriefCase type 1', { exact: true }).selectOption('ID Document');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('saved in this synthetic workspace');
  await page.goto('/preview');
  await page.getByLabel('SmartAdvocate case number').fill('SA-10428');
  await page.getByRole('button', { name: 'Run preview', exact: true }).click();
  await page.getByRole('tab', { name: 'Documents', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'Protected type', exact: true })).toHaveCount(2);
  await expect(page.getByRole('cell', { name: 'ID Document', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Reveal values' }).click();
  await expect(page.getByRole('cell', { name: 'Signed Retainer Agreement', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'ID Document', exact: true })).toBeVisible();
  await page.screenshot({ path: '../../artifacts/ui/document-types-preview.png', fullPage: true });
  await page.goto('/configuration');
  await page.getByLabel('BriefCase type 1', { exact: true }).selectOption('Signed Retainer Agreement');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('saved in this synthetic workspace');
});
